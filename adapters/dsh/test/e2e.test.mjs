import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, appendFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { DshBridge } from '../src/bridge.mjs';
import { createAuthority, approvePlan } from '../src/approval.mjs';
import { serveBridge } from '../src/server.mjs';
import { DshBridgeClient } from '../src/client.mjs';
import { atomicJson, digest } from '../src/common.mjs';
import { snapshotProfile } from '../src/profile.mjs';

const install = process.env.HEREIN_DSH_INSTALL || 'C:/Users/wzy_8/AppData/Local/Programs/DeepSeek Harness';
const fixture = name => resolve(import.meta.dirname, '../fixtures', name);
async function operator(client, keys, request) {
  const plan = await client.prepare(request);
  return client.execute(plan.id, approvePlan(plan, keys.privateKey, 'test operator'), randomUUID());
}
test('real DSH lifecycle through the C-facing HTTP client, approval and failure recovery', { timeout: 240000 }, async t => {
  const root = await mkdtemp(join(tmpdir(), 'herein-dsh-e2e-')), keys = createAuthority(), token = randomBytes(32).toString('base64url');
  let bridge = await DshBridge.open({ root, install, publicKey: keys.publicKey });
  let server = await serveBridge(bridge, { token });
  let client = new DshBridgeClient({ url: server.url, token });
  t.after(async () => { await server?.close(); await bridge?.close(); });
  const evidence = [];
  const change = async request => { const value = await operator(client, keys, request); evidence.push({ action: request.action, application: value.application, errorCode: value.errorCode, recovery: value.recovery, snapshotId: value.snapshotId }); return value; };
  assert.equal((await client.health()).runtimeVersion, '0.2.1-rc.2');
  assert.equal((await fetch(server.url + '/health')).status, 401);
  assert.equal((await fetch(server.url + '/health', { headers: { Authorization: 'Bearer ' + token, Origin: 'https://evil.test' } })).status, 401);
  await assert.rejects(DshBridge.open({ root, install, publicKey: keys.publicKey }), { code: 'BRIDGE_LOCKED' });
  let plan = await client.prepare({ action: 'install', target: fixture('hello-v1'), enabled: false });
  await assert.rejects(client.execute(plan.id, undefined), { code: 'APPROVAL_INVALID' });
  const operationId = randomUUID(), grant = approvePlan(plan, keys.privateKey, 'test operator');
  const installed = await client.execute(plan.id, grant, operationId);
  assert.equal(installed.application, 'applied');
  assert.equal((await client.execute(plan.id, grant, operationId)).snapshotId, installed.snapshotId);
  await assert.rejects(client.execute(plan.id, grant, randomUUID()), { code: 'APPROVAL_REPLAY' });
  assert.equal((await client.inventory()).capabilities.length, 0);
  assert.equal((await change({ action: 'setBundle', target: '@herein/dsh-hello', enabled: true })).application, 'applied');
  let inventory = await client.inventory();
  assert.equal(inventory.capabilities[0].name, 'herein_hello');
  assert.equal(inventory.capabilities[0].parameters.required[0], 'name');
  assert.equal((await client.call('herein_hello', { name: 'Herein' })).value, 'hello Herein (v1)');
  assert.equal((await change({ action: 'restart' })).application, 'applied');
  assert.equal((await client.call('herein_hello', { name: 'Herein' })).value, 'hello Herein (v1)');
  assert.equal((await client.call('herein_hello', { name: 123 })).error.info.code, 'INVALID_ARGS');
  const plugin = inventory.plugins.find(row => row.moduleName === '@herein/dsh-hello');
  const disabled = await change({ action: 'setPlugin', target: plugin.entryId, enabled: false });
  assert.equal(disabled.application, 'applied');
  assert.equal((await client.call('herein_hello', { name: 'Herein' })).error.info.code, 'UNKNOWN_TOOL');
  assert.equal((await change({ action: 'rollback', snapshotId: disabled.snapshotId })).application, 'applied');
  assert.equal((await client.call('herein_hello', { name: 'Herein' })).value, 'hello Herein (v1)');
  const updated = await change({ action: 'update', target: fixture('hello-v2'), enabled: true });
  assert.equal(updated.application, 'applied');
  assert.equal((await client.call('herein_hello', { name: 'Herein' })).value, 'hello Herein (v2)');
  assert.equal((await change({ action: 'rollback', snapshotId: updated.snapshotId })).application, 'applied');
  assert.equal((await client.call('herein_hello', { name: 'Herein' })).value, 'hello Herein (v1)');
  const bad = join(root, 'bad-fixture'); await mkdir(bad);
  await writeFile(join(bad, 'package.json'), JSON.stringify({ name: '@herein/broken', version: '1.0.0', private: true, type: 'module', exports: { '.': './index.js' }, dsh: { bundle: { patch: './cordis.patch.yml' } } }));
  await writeFile(join(bad, 'cordis.patch.yml'), '- insert:\n    - id: herein-broken\n      name: "@herein/broken"\n');
  await writeFile(join(bad, 'index.js'), 'export function apply() { throw new Error("FAKE_SECRET_DO_NOT_LOG_91"); }');
  const before = await bridge.stateHash();
  const failed = await change({ action: 'install', target: bad, enabled: true });
  assert.equal(failed.application, 'failed'); assert.equal(failed.recovery.status, 'restored');
  assert.equal(await bridge.stateHash(), before);
  assert.equal((await client.call('herein_hello', { name: 'Herein' })).value, 'hello Herein (v1)');
  assert.ok(!(await client.inventory()).bundles.some(row => row.name === '@herein/broken'));
  assert.ok(!JSON.stringify(await client.audit()).includes('FAKE_SECRET_DO_NOT_LOG_91'));
  const remove = await change({ action: 'remove', target: '@herein/dsh-hello' }); assert.equal(remove.application, 'applied');
  assert.equal((await client.inventory()).capabilities.length, 0);
  await change({ action: 'rollback', snapshotId: remove.snapshotId });
  await server.close(); server = undefined; await bridge.close();
  bridge = await DshBridge.open({ root, install, publicKey: keys.publicKey });
  server = await serveBridge(bridge, { token }); client = new DshBridgeClient({ url: server.url, token });
  assert.equal((await client.call('herein_hello', { name: 'Herein' })).value, 'hello Herein (v1)');
  assert.equal((await client.result(operationId)).application, 'applied');
  const audit = await client.audit();
  assert.ok(audit.records.some(row => row.event === 'approval.denied'));
  assert.ok(audit.records.filter(row => row.event === 'host.started').length >= 4);
  console.log(JSON.stringify({ evidence, auditRecords: audit.records.length, root }));
});
